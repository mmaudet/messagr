/**
 * The emoji a person can react with, arranged the way a picker shows them.
 *
 * # WHY A LIST AND NOT THE UNICODE TABLE
 *
 * WhatsApp opens the system's own emoji keyboard, which is every emoji the
 * telephone knows -- around 3,800 of them, plus skin tones, plus the ones
 * this year's Unicode added and last year's telephone cannot draw. Shipping
 * that means shipping a data file, a search index and a set of fallbacks for
 * the glyphs a given Android build renders as a hollow box.
 *
 * This is the same decision `LANGUAGES` makes: name what the product offers,
 * write down why, and let the list be read. A reaction is a small gesture --
 * agreeing, laughing, saying "seen" without saying anything -- and the ones
 * below cover it several times over. What is lost is the seventy-third
 * variant of a face; what is gained is a picker that opens instantly, draws
 * on every device, and has no dependency behind it.
 *
 * The six on the bubble itself stay exactly what they were. This is what the
 * `+` beside them opens.
 *
 * # ORDER, AND WHY IT IS NOT ALPHABETICAL
 *
 * Emoji have no alphabet. They are grouped the way every keyboard groups
 * them and in the order every keyboard uses, because the point of a picker
 * is that a thumb already knows where to go.
 */

